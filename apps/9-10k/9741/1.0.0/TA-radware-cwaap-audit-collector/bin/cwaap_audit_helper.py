#
# ucc-gen generates bin/cwaap_audit.py (the modular-input entry point) and
# calls validate_input() / stream_events() from this module. The collection
# logic lives in input_module_cwaap_audit.py and is shared with the offline
# test-suite; this file only adapts the Splunk runtime (solnlib credential
# store, KV-store checkpoints, proxy settings, event writer) to the small
# helper interface that module expects.

from __future__ import annotations

import json
import logging
import traceback
from typing import Any, Dict, List, Optional

import import_declare_test  # noqa: F401  (generated by ucc-gen; fixes sys.path)

import requests
from solnlib import conf_manager, log
from solnlib.credentials import CredentialManager, CredentialNotExistException
from solnlib.modular_input.checkpointer import KVStoreCheckpointer
from splunklib import modularinput as smi

import input_module_cwaap_audit as core

ADDON_NAME            = "TA-radware-cwaap-audit-collector"
INPUT_TYPE            = "cwaap_audit"
SETTINGS_CONF         = "ta_radware_cwaap_audit_collector_settings"
CHECKPOINT_COLLECTION = "TA_radware_cwaap_audit_collector_checkpointer"
LOGGER_NAME           = "ta_radware_cwaap_audit_collector_cwaap_audit"
ENCRYPTED_FIELDS      = ("api_key",)
MASK                  = "******"


def _logger(input_name: str) -> logging.Logger:
    return log.Logs().get_logger(LOGGER_NAME)


class SplunkHelper:
    """Adapter exposing the helper API used by the core module."""

    def __init__(self, input_name: str, params: Dict[str, Any], session_key: str, logger: logging.Logger):
        self.input_name = input_name
        self.params = dict(params)
        self.session_key = session_key
        self.logger = logger
        self._level = logging.getLevelName(logger.level) if logger.level else "INFO"
        self._secrets: Optional[Dict[str, str]] = None
        self._checkpointer: Optional[KVStoreCheckpointer] = None
        self._proxies: Optional[Dict[str, str]] = None
        self._proxies_loaded = False

    # ---- logging -----------------------------------------------------------
    def get_log_level(self) -> str:
        return self._level

    def set_log_level(self, level) -> None:
        if isinstance(level, str) and level:
            self._level = level.upper()
            self.logger.setLevel(self._level)

    def log_debug(self, msg):   self.logger.debug(msg)
    def log_info(self, msg):    self.logger.info(msg)
    def log_warning(self, msg): self.logger.warning(msg)
    def log_error(self, msg):   self.logger.error(msg)

    # ---- stanza / arguments ------------------------------------------------
    def get_input_stanza_names(self) -> List[str]:
        return [self.input_name]

    def get_interval(self) -> int:
        try:
            return int(float(self.params.get("interval") or 300))
        except (TypeError, ValueError):
            return 300

    def get_output_index(self) -> str:
        return self.params.get("index") or "default"

    def get_arg(self, name: str):
        value = self.params.get(name)
        if name in ENCRYPTED_FIELDS and (value in (None, "", MASK)):
            value = self._secret(name)
        return value

    def _secret(self, name: str) -> Optional[str]:
        """Encrypted input fields are stored by the UCC REST handler as JSON
        under a fixed realm in passwords.conf."""
        if self._secrets is None:
            self._secrets = {}
            realm = f"__REST_CREDENTIAL__#{ADDON_NAME}#data/inputs/{INPUT_TYPE}"
            try:
                raw = CredentialManager(self.session_key, ADDON_NAME, realm=realm).get_password(self.input_name)
                loaded = json.loads(raw) if raw and raw.strip().startswith("{") else {}
                if isinstance(loaded, dict):
                    self._secrets = {k: str(v) for k, v in loaded.items()}
            except CredentialNotExistException:
                self.logger.error(f"No stored credential found for input '{self.input_name}' (realm {realm})")
            except Exception as exc:                    # pragma: no cover
                self.logger.error(f"Failed to read stored credential for input '{self.input_name}': {exc}")
        return self._secrets.get(name)

    # ---- checkpoints (KV store) --------------------------------------------
    def _cp(self) -> KVStoreCheckpointer:
        if self._checkpointer is None:
            self._checkpointer = KVStoreCheckpointer(CHECKPOINT_COLLECTION, self.session_key, ADDON_NAME)
        return self._checkpointer

    def get_check_point(self, key: str):
        try:
            return self._cp().get(key)
        except Exception as exc:
            self.logger.warning(f"checkpoint read failed for '{key}': {exc}")
            return None

    def save_check_point(self, key: str, value) -> None:
        try:
            self._cp().update(key, value)
        except Exception as exc:
            self.logger.error(f"checkpoint write failed for '{key}': {exc}")

    # ---- HTTP with the add-on proxy settings --------------------------------
    def _proxy_settings(self) -> Optional[Dict[str, str]]:
        if self._proxies_loaded:
            return self._proxies
        self._proxies_loaded = True
        try:
            cfm = conf_manager.ConfManager(
                self.session_key, ADDON_NAME,
                realm=f"__REST_CREDENTIAL__#{ADDON_NAME}#configs/conf-{SETTINGS_CONF}")
            proxy = cfm.get_conf(SETTINGS_CONF).get("proxy") or {}
        except Exception as exc:
            self.logger.debug(f"no proxy settings available: {exc}")
            return None
        enabled = str(proxy.get("proxy_enabled", "0")).lower() in ("1", "true", "yes")
        host, port = proxy.get("proxy_url"), proxy.get("proxy_port")
        if not (enabled and host and port):
            return None
        scheme = (proxy.get("proxy_type") or "http").lower()
        if scheme.startswith("socks") and str(proxy.get("proxy_rdns", "0")).lower() in ("1", "true", "yes"):
            scheme = scheme + "h"                       # remote DNS resolution
        auth = ""
        if proxy.get("proxy_username"):
            auth = requests.utils.quote(str(proxy["proxy_username"]), safe="")
            if proxy.get("proxy_password"):
                auth += ":" + requests.utils.quote(str(proxy["proxy_password"]), safe="")
            auth += "@"
        url = f"{scheme}://{auth}{host}:{port}"
        self._proxies = {"http": url, "https": url}
        self.logger.info(f"using {scheme} proxy {host}:{port}")
        return self._proxies

    def send_http_request(self, url, method, payload=None, headers=None, timeout=30,
                          verify=True, use_proxy=True, **_ignored):
        proxies = self._proxy_settings() if use_proxy else None
        return requests.request(method, url, data=payload, headers=headers,
                                timeout=timeout, verify=verify, proxies=proxies)

    # ---- events ------------------------------------------------------------
    def new_event(self, data, time=None, source=None, sourcetype=None, index=None, **_ignored):
        return smi.Event(data=data, time=time, source=source, sourcetype=sourcetype,
                         index=index or self.get_output_index())


