def validate_input(definition: smi.ValidationDefinition):
    core.validate_input(None, definition)


def stream_events(inputs: smi.InputDefinition, event_writer: smi.EventWriter):
    session_key = inputs.metadata["session_key"]
    for input_name, input_item in inputs.inputs.items():
        normalized = input_name.split("/")[-1]
        logger = _logger(normalized)
        try:
            level = conf_manager.get_log_level(logger=logger, session_key=session_key,
                                               app_name=ADDON_NAME, conf_name=SETTINGS_CONF)
            logger.setLevel(level)
        except Exception:
            level = "INFO"
        log.modular_input_start(logger, normalized)
        helper = SplunkHelper(normalized, input_item, session_key, logger)
        helper.set_log_level(level if isinstance(level, str) else logging.getLevelName(level))
        try:
            written = _CountingWriter(event_writer)
            core.collect_events(helper, written)
            for (sourcetype, index), n in written.counts.items():
                log.events_ingested(logger, input_name, sourcetype, n, index)
        except Exception as exc:
            logger.error(f"[{normalized}] collection failed: {exc}\n{traceback.format_exc()}")
        log.modular_input_end(logger, normalized)


class _CountingWriter:
    """Pass-through event writer that counts events per (sourcetype, index)."""

    def __init__(self, ew: smi.EventWriter):
        self._ew = ew
        self.counts: Dict[Any, int] = {}

    def write_event(self, event: smi.Event):
        self._ew.write_event(event)
        key = (getattr(event, "sourceType", None), getattr(event, "index", None))
        self.counts[key] = self.counts.get(key, 0) + 1
